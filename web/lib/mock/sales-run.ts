const OBS_BY_CALL: Record<string, ObsType> = {
  search: "retriever",
  get_record: "retriever",
  compute: "tool",
  draft: "llm",
  notify: "tool",
  plan: "llm",
  respond: "llm",
};

let clock = 0;
const turns: Turn[] = drafts.map((d) => {
  const startOffsetMs = clock;
  clock += d.durationMs;
  const fn = d.call?.split("(")[0] ?? "";
  const obsType: ObsType =
    d.kind === "user" ? "chain" : d.kind === "human" ? "event" : (OBS_BY_CALL[fn] ?? "tool");
  return { ...d, obsType, startOffsetMs, parentIndex: d.index === 0 ? undefined : 0 };
});

